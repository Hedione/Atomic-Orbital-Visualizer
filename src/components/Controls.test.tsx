it.each(['real', 'complex'] as const)('disables all remaining transition controls for degenerate %s states and recovers with a new n', orbitalBasis => {
  render(<Harness initial={{ ...defaultSettings, orbitalBasis }} />)
  fireEvent.click(screen.getByRole('button', { name: 'Switch to Transition mode' }))
  fireEvent.click(screen.getByRole('button', { name: 'I understand' }))
  edit('n', 2); edit('ℓ', 1)
  fireEvent.click(screen.getByRole('button', { name: 'Final n = 2' }))
  expect(screen.getByTestId('transition-validation').textContent).toBe('These states are degenerate in this model: no finite-frequency resonant photon.')
  for (const name of ['Transition selections', 'Transition playback controls']) {
    const group = screen.getByRole('group', { name })
    expect(group.querySelectorAll('button, input').length).toBeGreaterThan(0)
    expect([...group.querySelectorAll('button, input')].every(element => element.matches(':disabled'))).toBe(true)
  }
  expect(screen.getByRole('button', { name: 'Final n = 3' }).matches(':disabled')).toBe(false)
  expect(screen.getByRole('spinbutton', { name: 'n' }).matches(':disabled')).toBe(false)
  fireEvent.click(screen.getByRole('button', { name: 'Final n = 3' }))
  expect(screen.queryByTestId('transition-validation')).toBeNull()
  expect(screen.getByRole('button', { name: 'Δℓ = +1' }).matches(':disabled')).toBe(false)
  expect(screen.getByRole('button', { name: 'Loop mode' }).matches(':disabled')).toBe(false)
  expect(screen.getByRole('slider', { name: 'Rabi Ω : light ω multiple' }).matches(':disabled')).toBe(false)
})

it.each(['real', 'complex'] as const)('remembers independent static and %s transition entries across repeated switches', orbitalBasis => {
  render(<Harness initial={{ ...defaultSettings, orbitalBasis }} />)
  edit('n', 4); edit('ℓ', 2)
  fireEvent.click(screen.getByRole('button', { name: 'Switch to Transition mode' }))
  fireEvent.click(screen.getByRole('button', { name: 'I understand' }))
  edit('n', 3); edit('ℓ', 1)
  if (orbitalBasis === 'real') fireEvent.change(screen.getByRole('slider', { name: 'Orbital' }), { target: { value: '1' } })
  else edit('mℓ', 1)
  fireEvent.click(screen.getByRole('button', { name: 'Final n = 4' }))
  fireEvent.click(screen.getByRole('button', { name: orbitalBasis === 'real' ? 'Final orbital d xy' : 'Δmℓ = −1' }))
  fireEvent.click(screen.getByRole('button', { name: 'Loop mode' }))
  fireEvent.change(screen.getByRole('slider', { name: 'Playback speed' }), { target: { value: '10000' } })
  fireEvent.change(screen.getByRole('slider', { name: 'Rabi Ω : light ω multiple' }), { target: { value: '7500' } })
  const entry = (s: Settings) => ({ n: s.n, l: s.l, m: s.m, n2: s.n2, l2: s.l2, m2: s.m2, orbitalBasis: s.orbitalBasis, polarization: s.polarization, rabiFrequency: s.rabiFrequency, transitionLoop: s.transitionLoop, transitionPlayback: s.transitionPlayback })
  const saved = entry(state())
  expect(saved.rabiFrequency).not.toBe(defaultRabiFrequency(state()))
  for (let i = 0; i < 2; i++) {
    fireEvent.click(screen.getByRole('button', { name: 'Switch to Static mode' }))
    expect(state().n).toBe(i === 0 ? 4 : 5)
    edit('n', 5)
    fireEvent.click(screen.getByRole('button', { name: 'Switch to Transition mode' }))
    expect(entry(state())).toEqual(saved)
    expect(state().transitionPlaying).toBe(false)
    expect(state().transitionProgress).toBe(0)
  }
  fireEvent.click(screen.getByRole('button', { name: 'Final n = 6' }))
  expect(state().rabiFrequency).toBe(defaultRabiFrequency(state()))
})
