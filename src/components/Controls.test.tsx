// @vitest-environment jsdom
import { afterEach, expect, it } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { useState } from 'react'
import { Controls, type UpdateSettings } from './Controls'
import { defaultSettings, type Orbital, type Settings } from '../types'
import { WavefunctionControls } from './SceneControls'
import { defaultRabiFrequency, validateTransition } from '../physics/transition'
afterEach(cleanup)

function Harness({ initial = defaultSettings }: { initial?: Settings }) {
  const [s, set] = useState(initial), [acknowledged, acknowledge] = useState(false)
  const update: UpdateSettings = (key, value) => set(previous => ({ ...previous, [key]: value }))
  const setState = (o: Orbital) => set(previous => ({ ...previous, ...o }))
  return <><Controls settings={s} update={update} setState={setState} transitionAcknowledged={acknowledged} acknowledgeTransition={() => acknowledge(true)} /><WavefunctionControls settings={s} update={update} /><output data-testid="state">{JSON.stringify(s)}</output></>
}
const state = (): Settings => JSON.parse(screen.getByTestId('state').textContent!)
const edit = (name: string, value: number) => {
  const field = screen.getByRole('spinbutton', { name })
  fireEvent.change(field, { target: { value: String(value) } }); fireEvent.blur(field)
}
it('clamps all dependent quantum numbers when n decreases', () => {
  render(<Harness initial={{ ...defaultSettings, orbitalBasis: 'complex' }} />)
  edit('n', 6); edit('ℓ', 5); edit('mℓ', -5); edit('n', 1)
  expect({ n: state().n, l: state().l, m: state().m }).toEqual({ n: 1, l: 0, m: 0 })
  expect(screen.queryByText('Particles & bond')).toBeNull()
})
it('extends to n=20 and restores the previous low-n selections', () => {
  render(<Harness initial={{ ...defaultSettings, orbitalBasis: 'complex' }} />)
  edit('n', 4)
  fireEvent.click(screen.getByRole('button', { name: 'Explore high n' }))
  edit('n', 20); edit('ℓ', 19); edit('mℓ', 19)
  expect(state().n).toBe(20)
  fireEvent.click(screen.getByRole('button', { name: 'Explore high n' }))
  expect(state().n).toBe(4); expect(state().highN).toBe(false)
})
it('keeps the secondary state disabled until superposition is enabled', () => {
  render(<Harness />)
  expect((screen.getByRole('spinbutton', { name: 'Second n' }) as HTMLInputElement).disabled).toBe(true)
  fireEvent.click(screen.getByRole('button', { name: 'Superposition mode' }))
  edit('Second n', 1)
  expect(state().n2).toBe(1); expect(state().l2).toBe(0); expect(state().m2).toBe(0)
})
it('enters an allowed 2p→3d transition and restores the static state on return', () => {
  render(<Harness initial={{ ...defaultSettings, orbitalBasis: 'complex' }} />)
  edit('n', 4)
  fireEvent.click(screen.getByRole('button', { name: 'Switch to Transition mode' }))
  fireEvent.click(screen.getByRole('button', { name: 'I understand' }))
  expect([state().n, state().l, state().m, state().n2, state().l2, state().m2]).toEqual([2, 1, 0, 3, 2, 0])
  fireEvent.click(screen.getByRole('button', { name: 'Δmℓ = +1' }))
  expect(state().polarization).toBe('sigmaPlus')
  expect(screen.queryByRole('spinbutton', { name: 'Final n' })).toBeNull()
  expect(screen.queryByRole('slider', { name: 'Final n' })).toBeNull()
  expect(within(screen.getByRole('group', { name: 'Final principal quantum number' })).getAllByRole('button')).toHaveLength(6)
  fireEvent.click(screen.getByRole('button', { name: 'Final n = 3' }))
  expect(state().n2).toBe(3)
  fireEvent.click(screen.getByRole('button', { name: 'Final n = 2' }))
  expect(state().n2).toBe(2)
  expect(screen.getByTestId('transition-validation').textContent).toBe('These states are degenerate in this model: no finite-frequency resonant photon.')
  expect((screen.getByRole('button', { name: 'Play transition' }) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.click(screen.getByRole('button', { name: 'Final n = 1' }))
  expect(screen.queryByTestId('transition-validation')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Switch to Static mode' }))
  expect(state().n).toBe(4)
})
it.each(['real', 'complex'] as const)('randomizes both states while respecting hydrogen bounds and %s dipole rules', orbitalBasis => {
  render(<Harness initial={{ ...defaultSettings, orbitalBasis }} />)
  fireEvent.click(screen.getByRole('button', { name: 'Switch to Transition mode' }))
  fireEvent.click(screen.getByRole('button', { name: 'I understand' }))
  for (let i = 0; i < 20; i++) {
    fireEvent.click(screen.getByRole('button', { name: 'Randomize' }))
    const s = state()
    expect(s.n).not.toBe(s.n2); expect(Math.abs(s.l - s.l2)).toBe(1)
    expect(validateTransition(s).allowed).toBe(true)
    expect(s.l).toBeLessThan(s.n); expect(s.l2).toBeLessThan(s.n2); expect(Math.abs(s.m)).toBeLessThanOrEqual(s.l); expect(Math.abs(s.m2)).toBeLessThanOrEqual(s.l2)
  }
})
it('offers the three real p orbitals and restores the complex quantum editor', () => {
  render(<Harness />)
  expect(state().orbitalBasis).toBe('real')
  expect(screen.queryByText(/Normalized combination/)).toBeNull()
  expect(screen.getByTestId('orbital-label').parentElement).toBe(screen.getByTestId('real-orbital-combination').parentElement)
  const formula = () => within(screen.getByTestId('real-orbital-combination')).getAllByRole('math')[0].getAttribute('aria-label')
  expect(formula()).toBe(String.raw`\psi_{\mathrm{real}} = \psi_{2,1,0}`)
  expect(screen.queryByRole('combobox')).toBeNull()
  const slider = screen.getByRole('slider', { name: 'Orbital' })
  expect(slider.getAttribute('min')).toBe('-1')
  expect(slider.getAttribute('max')).toBe('1')
  fireEvent.click(screen.getByRole('button', { name: 'Next orbital' }))
  expect(state().m).toBe(1)
  expect((screen.getByRole('button', { name: 'Next orbital' }) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.click(screen.getByRole('button', { name: 'Previous orbital' }))
  fireEvent.click(screen.getByRole('button', { name: 'Previous orbital' }))
  expect(state().m).toBe(-1)
  expect((screen.getByRole('button', { name: 'Previous orbital' }) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.change(slider, { target: { value: '1' } })
  expect(state().orbitalBasis).toBe('real'); expect(state().m).toBe(1)
  expect(screen.getByTestId('orbital-label').textContent).toBe('2px')
  expect(screen.getByTestId('orbital-label').querySelector('sub')?.textContent).toBe('x')
  expect(screen.getByLabelText('Orbital selection').querySelector('sub')?.textContent).toBe('x')
  expect(formula()).toBe(String.raw`\psi_{\mathrm{real}} = \frac{-\psi_{2,1,1} + \psi_{2,1,-1}}{\sqrt{2}}`)
  fireEvent.change(slider, { target: { value: '-1' } })
  expect(formula()).toBe(String.raw`\psi_{\mathrm{real}} = \frac{-\psi_{2,1,1} - \psi_{2,1,-1}}{i\sqrt{2}}`)
  fireEvent.change(slider, { target: { value: '1' } })
  expect(screen.queryByRole('spinbutton', { name: 'mℓ' })).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Real orbital combinations' }))
  expect(screen.queryByTestId('real-orbital-combination')).toBeNull()
  expect(screen.getByTestId('orbital-label').textContent).toBe('2p, mℓ=1')
  expect((screen.getByRole('spinbutton', { name: 'mℓ' }) as HTMLInputElement).value).toBe('1')
})
