import { expect, test } from '@playwright/test'
import { selectMode } from './modes'

test('animated mode picker separates modules, remembers entries, and supports field shifts', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  const trigger = page.getByRole('button', { name: 'Simulation mode', exact: true })
  const choices = page.getByRole('group', { name: 'Simulation modes', exact: true })
  await expect(trigger).toContainText('Static mode')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('.mode-controls h2, .mode-controls .section-number')).toHaveCount(0)
  await expect(trigger.locator('strong')).toHaveCSS('color', 'rgb(255, 155, 73)')
  await expect(trigger.locator('svg')).toHaveCSS('color', 'rgb(255, 133, 31)')
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toHaveCount(0)
  await expect(page.getByRole('slider', { name: 'Second n', exact: true })).toHaveCount(0)
  await expect(page.getByRole('slider', { name: 'State mix', exact: true })).toHaveCount(0)
  await expect(page.getByRole('slider', { name: 'Number of samples', exact: true })).toBeVisible()
  await expect(page.getByRole('slider', { name: 'Sampling rate', exact: true })).toBeVisible()
  await expect(page.getByText('Electrons', { exact: true })).toHaveCount(0)
  await trigger.click()
  await expect(choices.getByRole('button')).toHaveCount(4)
  await expect(choices.getByRole('button', { name: 'Static mode', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(choices.getByRole('button', { name: 'Superposition mode', exact: true })).toHaveAttribute('aria-pressed', 'false')
  expect(await page.locator('.mode-picker-reveal').evaluate(element => getComputedStyle(element).transitionDuration)).toContain('0.18s')
  await choices.getByRole('button', { name: 'Superposition mode', exact: true }).hover()
  await expect.poll(() => choices.getByRole('button', { name: 'Superposition mode', exact: true }).evaluate(element => getComputedStyle(element).boxShadow)).not.toBe('none')
  for (const width of [1440, 1100, 720, 320]) {
    await page.setViewportSize({ width, height: 1050 })
    if (width <= 760) {
      const settings = page.getByRole('button', { name: 'SIMULATION SETTINGS', exact: true })
      if (await settings.getAttribute('aria-expanded') === 'false') await settings.click()
    }
    await trigger.scrollIntoViewIfNeeded()
    if (await trigger.getAttribute('aria-expanded') === 'false') await trigger.click()
    await page.locator('.mode-picker-reveal').evaluate(async element => { await Promise.all(element.getAnimations().map(animation => animation.finished)) })
    const boxes = await choices.getByRole('button').evaluateAll(elements => elements.map(element => {
      const box = element.getBoundingClientRect()
      return { x: box.x, y: box.y, width: box.width, height: box.height, fits: element.scrollWidth <= element.clientWidth && element.scrollHeight <= element.clientHeight }
    }))
    expect(boxes.every(box => Math.abs(box.width - boxes[0].width) < 1 && box.height === 56 && box.fits)).toBe(true)
    expect(boxes[0].y).toBeCloseTo(boxes[1].y, 0)
    expect(boxes[2].y).toBeCloseTo(boxes[3].y, 0)
    expect(boxes[2].y).toBeGreaterThan(boxes[0].y)
    await page.locator('.mode-picker').screenshot({ path: `test-results/mode-picker-${width}.png` })
  }
  await choices.getByRole('button', { name: 'Superposition mode', exact: true }).press('Escape')
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await page.setViewportSize({ width: 1440, height: 1050 })
  await selectMode(page, 'Superposition mode')
  await expect(page.locator('.mode-controls h2, .mode-controls .section-number')).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toBeVisible()
  await page.getByRole('slider', { name: 'n', exact: true }).fill('4')
  await page.getByRole('slider', { name: 'State mix', exact: true }).fill('25')
  await selectMode(page, 'Static mode')
  await expect(page.getByRole('slider', { name: 'n', exact: true })).toHaveAttribute('aria-valuenow', '2')
  await selectMode(page, 'Transition mode')
  await page.getByRole('button', { name: 'I understand', exact: true }).click()
  await expect(page.locator('.mode-controls h2, .mode-controls .section-number')).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Final n = 4', exact: true }).click()
  await page.getByRole('slider', { name: 'π-pulse progress', exact: true }).fill('50')
  await selectMode(page, 'Transition mode')
  await expect.poll(async () => Number(await page.getByRole('slider', { name: 'π-pulse progress', exact: true }).getAttribute('aria-valuenow'))).toBeCloseTo(50, 9)
  await selectMode(page, 'Stark / Zeeman')
  await expect(page.getByRole('region', { name: 'Stark and Zeeman shifts' })).toBeVisible()
  await expect(page.locator('canvas')).toHaveCount(0)
  await expect(page.getByRole('spinbutton', { name: 'Field shell n', exact: true })).toBeVisible()
  await selectMode(page, 'Superposition mode')
  await expect(page.getByRole('slider', { name: 'n', exact: true })).toHaveAttribute('aria-valuenow', '4')
  await expect(page.getByRole('slider', { name: 'State mix', exact: true })).toHaveAttribute('aria-valuenow', '25')
  await expect(page.locator('canvas')).toHaveCount(3)
  await selectMode(page, 'Transition mode')
  await expect(page.getByRole('button', { name: 'Final n = 4', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('slider', { name: 'π-pulse progress', exact: true })).toHaveAttribute('aria-valuenow', '0')
  await page.getByRole('button', { name: 'RESET SIMULATION', exact: true }).click()
  await expect(trigger).toContainText('Static mode')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await trigger.click()
  expect(await page.locator('.mode-picker-reveal').evaluate(element => getComputedStyle(element).transitionDuration)).toBe('0s')
  await choices.getByRole('button', { name: 'Static mode', exact: true }).click()
  expect(errors).toEqual([])
})
