import { expect, test } from '@playwright/test'
import { selectMode } from './modes'

test('Space toggles sampling after clicking sliders without scrolling or changing their values', async ({ page }) => {
  await page.goto('/')
  for (const viewport of [{ width: 1440, height: 1050 }, { width: 720, height: 700 }]) {
    await page.setViewportSize(viewport)
    for (const name of ['Sampling rate', 'Volume brightness']) {
      const slider = page.getByRole('slider', { name, exact: true })
      await slider.click()
      await expect(slider).toBeFocused()
      const value = await slider.inputValue()
      const scroll = await page.evaluate(() => window.scrollY)
      await page.keyboard.down('Space')
      await page.keyboard.down('Space')
      await page.keyboard.up('Space')
      await expect(page.getByRole('button', { name: 'Resume sampling', exact: true })).toBeVisible()
      await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
      expect(await page.evaluate(() => window.scrollY)).toBe(scroll)
      await expect(slider).toHaveValue(value)
      await expect(slider).toBeFocused()
      await page.keyboard.press('Space')
      await expect(page.getByRole('button', { name: 'Pause sampling', exact: true })).toBeVisible()
      await expect(slider).toHaveValue(value)
      if (name === 'Sampling rate') {
        await slider.press('ArrowLeft')
        await expect(slider).not.toHaveValue(value)
      }
    }
  }
})

test('information dialog follows the guide and keeps focus, dismissal, and mobile content usable', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  const trigger = page.getByRole('button', { name: 'About this simulation', exact: true })
  const dialog = page.getByRole('dialog', { name: 'A laboratory for hydrogen orbitals' })
  const close = page.getByRole('button', { name: 'Close information', exact: true })
  await trigger.focus()
  await page.keyboard.press('Space')
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Pause sampling', exact: true })).toBeVisible()
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: 'Resume sampling', exact: true })).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(dialog).toBeVisible()
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(close).toBeFocused()
  const repository = dialog.getByRole('link', { name: 'project on GitHub' })
  await expect(repository).toHaveAttribute('href', 'https://github.com/Hedione/Atomic-Orbital-Visualizer')
  await expect(repository).toHaveAttribute('target', '_blank')
  await expect(repository).toHaveAttribute('rel', 'noopener noreferrer')
  await expect(dialog.locator('kbd')).toHaveText(['Space', 'R', 'W', '/'])
  await page.keyboard.press('Tab')
  await expect(repository).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(repository).toBeFocused()
  await page.keyboard.press('w')
  await page.keyboard.press('r')
  await page.keyboard.press('/')
  await expect(page.getByRole('button', { name: 'Wavefunction', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-n', '2')
  const bounds = await dialog.boundingBox()
  await page.mouse.click(bounds!.x + 5, bounds!.y + 5)
  await expect(dialog).toBeVisible()
  await page.screenshot({ path: 'test-results/information-desktop.png' })
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.mouse.click(4, 4)
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await close.press('Space')
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')

  await page.setViewportSize({ width: 320, height: 480 })
  await trigger.click()
  await expect(dialog).toBeVisible()
  const layout = await dialog.evaluate(element => {
    const style = getComputedStyle(element), rect = element.getBoundingClientRect()
    return { left: rect.left, right: rect.right, top: rect.top, bottom: rect.bottom, padding: style.padding, overflow: element.scrollWidth > element.clientWidth, columns: getComputedStyle(element.querySelector('dl')!).gridTemplateColumns.split(' ').length }
  })
  expect(layout.left).toBeGreaterThanOrEqual(28)
  expect(layout.right).toBeLessThanOrEqual(292)
  expect(layout.top).toBeGreaterThanOrEqual(28)
  expect(layout.bottom).toBeLessThanOrEqual(452)
  expect(layout.padding).toBe('30px')
  expect(layout.overflow).toBe(false)
  expect(layout.columns).toBe(1)
  await dialog.locator('dd').last().scrollIntoViewIfNeeded()
  await expect(dialog.locator('dd').last()).toBeInViewport()
  await page.screenshot({ path: 'test-results/information-mobile.png' })
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

test('Space, R, W, and slash operate existing controls in the applicable modes', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.locator('body').click({ position: { x: 5, y: 80 } })
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: 'Resume sampling', exact: true })).toBeVisible()
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: 'Pause sampling', exact: true })).toBeVisible()
  await page.keyboard.press('Space')
  const real = page.getByRole('button', { name: 'Real component', exact: true })
  await real.focus()
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: 'Pause sampling', exact: true })).toBeVisible()
  await expect(real).toHaveAttribute('aria-pressed', 'false')
  const randomize = page.getByRole('button', { name: 'Randomize', exact: true })
  await randomize.focus()
  await page.keyboard.down('Space')
  await page.keyboard.down('Space')
  await page.keyboard.up('Space')
  await expect(page.getByRole('button', { name: 'Resume sampling', exact: true })).toBeVisible()
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-n', '2')
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-l', '1')
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-m', '0')
  await expect(randomize).toBeFocused()
  await real.press('Enter')
  await expect(real).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Wavefunction', exact: true }).click()
  for (const name of ['Probability density', 'Real component', 'Imaginary component', 'Wavefunction']) {
    await page.keyboard.press('w')
    await expect(page.getByRole('button', { name, exact: true })).toHaveAttribute('aria-pressed', 'true')
  }
  const n = page.getByRole('spinbutton', { name: 'n', exact: true })
  await n.focus()
  await page.keyboard.press('w')
  await expect(page.getByRole('button', { name: 'Wavefunction', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await n.blur()
  await page.evaluate(() => {
    const random = Math.random
    Math.random = () => 0.5
    document.body.dispatchEvent(new KeyboardEvent('keydown', { key: 'R', bubbles: true }))
    Math.random = random
  })
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-n', '4')
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-l', '2')
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-m', '0')
  await page.keyboard.press('/')
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toHaveCount(0)

  await selectMode(page, 'Superposition mode')
  await page.keyboard.press('/')
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('/')
  await expect(page.getByRole('tab', { name: 'Bohr orbit', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('r')
  const stage = page.locator('.unified-stage')
  await expect(stage).toHaveAttribute('data-superposition', 'true')
  for (const attribute of ['data-displayed-n', 'data-displayed-n2']) {
    const value = Number(await stage.getAttribute(attribute))
    expect(value).toBeGreaterThanOrEqual(1)
    expect(value).toBeLessThanOrEqual(6)
  }

  await selectMode(page, 'Transition mode')
  await page.getByRole('button', { name: 'I understand', exact: true }).click()
  await page.keyboard.press('/')
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('/')
  await expect(page.getByRole('tab', { name: 'Field & dipole', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('r')
  const firstN = Number(await stage.getAttribute('data-displayed-n'))
  const secondN = Number(await page.getByRole('group', { name: 'Final principal quantum number' }).locator('[aria-pressed="true"]').textContent())
  expect(firstN).not.toBe(secondN)
  await expect(page.getByRole('button', { name: 'Play transition', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'RESET SIMULATION' }).click()
  await page.keyboard.press('w')
  await expect(page.getByRole('button', { name: 'Probability density', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(errors).toEqual([])
})
