import { expect, test, type Page } from '@playwright/test'
import { selectMode } from './modes'

async function chooseState(page: Page, labelPart: string) {
  const selector = page.getByRole('combobox', { name: 'Selected field state', exact: true })
  const option = selector.locator('option').filter({ hasText: labelPart }).first()
  await selector.selectOption((await option.getAttribute('value'))!)
}

test('field shifts show the Stark quartet, spin splitting, quadratic 1s, and parallel fields', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await selectMode(page, 'Stark / Zeeman')
  await expect(page.getByRole('region', { name: 'Stark and Zeeman shifts', exact: true })).toBeVisible()
  await expect(page.locator('canvas')).toHaveCount(0)
  const selected = page.getByTestId('shift-selected')
  const correction = async () => Number(await selected.getAttribute('data-shift-ev'))
  await expect(page.getByTestId('shift-state-count')).toHaveText('6')
  await expect(page.getByTestId('shift-energy-count')).toHaveText('5')
  expect(await correction()).toBeCloseTo(-2 * 5.7883817982e-5, 14)
  await page.getByRole('slider', { name: 'Magnetic field', exact: true }).fill('0.5')
  expect(await correction()).toBeCloseTo(-5.7883817982e-5, 14)
  await page.getByRole('button', { name: 'Select spin +½', exact: true }).click()
  await expect(page.getByTestId('shift-state-count')).toHaveText('3')
  await expect(page.getByTestId('shift-state-label')).toContainText('mₛ = +½')
  await page.getByRole('button', { name: 'Electron spin', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Spin projection', exact: true })).toHaveCount(0)
  await expect(page.getByTestId('shift-state-label')).toContainText('orbital only')
  await page.getByRole('button', { name: 'Stark n = 2', exact: true }).click()
  await expect(page.getByTestId('shift-state-count')).toHaveText('8')
  await expect(page.getByTestId('shift-energy-count')).toHaveText('3')
  await expect(page.getByRole('spinbutton', { name: 'Field orbital ℓ', exact: true })).toBeDisabled()
  await expect(page.getByRole('slider', { name: 'Magnetic field', exact: true })).toBeDisabled()
  await chooseState(page, 'n₁ = 0, n₂ = 1')
  expect(await correction()).toBeCloseTo(-3 * 5.29177210544e-11 * 10000, 16)
  await page.getByRole('slider', { name: 'Electric field', exact: true }).fill('-10')
  expect(await correction()).toBeCloseTo(3 * 5.29177210544e-11 * 10000, 16)
  const shell = page.getByRole('spinbutton', { name: 'Field shell n', exact: true })
  await shell.fill('1'); await shell.press('Enter')
  await expect(page.getByTestId('shift-state-count')).toHaveText('2')
  await expect(page.getByTestId('shift-energy-count')).toHaveText('1')
  const groundShift = -2.25 * 27.211386245981 * (10000 / 5.14220675112e11) ** 2
  expect(await correction()).toBeCloseTo(groundShift, 24)
  await page.getByRole('slider', { name: 'Electric field', exact: true }).fill('10')
  expect(await correction()).toBeCloseTo(groundShift, 24)
  await page.getByRole('button', { name: 'Parallel n = 3', exact: true }).click()
  await expect(page.getByTestId('shift-state-count')).toHaveText('18')
  await chooseState(page, 'n₁ = 2, n₂ = 0')
  const electric = Number(await selected.getAttribute('data-stark-ev')), magnetic = Number(await selected.getAttribute('data-zeeman-ev'))
  expect(electric).toBeCloseTo(9 * 5.29177210544e-11 * 10000, 16)
  expect(await correction()).toBeCloseTo(electric + magnetic, 16)
  await page.getByRole('button', { name: 'Frequency units', exact: true }).click()
  await expect(selected).toContainText('MHz')
  expect(await correction()).toBeCloseTo(electric + magnetic, 16)
  await page.getByRole('button', { name: 'Zero fields', exact: true }).click()
  await expect(page.getByTestId('shift-energy-count')).toHaveText('1')
  await expect(page.locator('.shift-branch')).toHaveCount(1)
  expect(await correction()).toBe(0)
  await selectMode(page, 'Static mode')
  await expect(page.getByRole('slider', { name: 'n', exact: true })).toHaveAttribute('aria-valuenow', '2')
  await selectMode(page, 'Stark / Zeeman')
  await expect(shell).toHaveValue('3')
  await expect(page.getByRole('slider', { name: 'Magnetic field', exact: true })).toHaveAttribute('aria-valuenow', '0')
  await page.getByRole('button', { name: 'RESET SIMULATION', exact: true }).click()
  await selectMode(page, 'Stark / Zeeman')
  await expect(shell).toHaveValue('2')
  await expect(page.getByRole('slider', { name: 'Magnetic field', exact: true })).toHaveAttribute('aria-valuenow', '1')
  await expect(page.getByRole('button', { name: 'Energy units', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(errors).toEqual([])
})

test('field prototype keeps readable plots, scrolling states, and controls across screen sizes', async ({ page }) => {
  test.setTimeout(120000)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await selectMode(page, 'Stark / Zeeman')
  await page.getByRole('button', { name: 'Parallel n = 3', exact: true }).click()
  const shell = page.getByRole('spinbutton', { name: 'Field shell n', exact: true })
  await shell.fill('6'); await shell.press('Enter')
  await expect(page.getByTestId('shift-state-count')).toHaveText('72')
  await expect(page.locator('.shift-state-table tbody tr')).toHaveCount(72)
  await page.evaluate(() => document.fonts.ready)
  for (const width of [1440, 1100, 720, 320]) {
    await page.setViewportSize({ width, height: 1050 })
    const settings = page.getByRole('button', { name: 'SIMULATION SETTINGS', exact: true })
    if (await settings.isVisible() && await settings.getAttribute('aria-expanded') === 'false') await settings.click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    const controls = page.locator('.field-shift-controls')
    expect(await controls.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    await expect(shell).toBeVisible()
    if (await settings.isVisible() && await settings.getAttribute('aria-expanded') === 'true') await settings.click()
    const plot = page.getByRole('group', { name: 'Energy splitting fan', exact: true })
    await expect.poll(() => plot.evaluate(element => Math.abs((element as SVGSVGElement).viewBox.baseVal.width - element.getBoundingClientRect().width))).toBeLessThan(1)
    expect(await plot.locator('text').first().evaluate(element => getComputedStyle(element).fontSize)).toBe('9px')
  }
  await page.getByRole('combobox', { name: 'Selected field state', exact: true }).selectOption({ index: 20 })
  await expect(page.getByTestId('shift-state-label')).toContainText('n = 6')
  await page.screenshot({ path: 'test-results/field-shifts-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.getByRole('button', { name: 'Stark n = 2', exact: true }).click()
  await chooseState(page, 'n₁ = 1, n₂ = 0')
  await page.screenshot({ path: 'test-results/field-shifts-desktop.png', fullPage: true })
})
